/** 上游词低质量判定：广告 / 网站名 / 截断词 / 品牌词 / 交易话术。 */
export function isLowQuality(word, category) {
  if (/[|*]/.test(word)) return true
  if (/^毛/.test(word) && word !== '毛片') return true
  if (category === 'gambling') {
    if (/^[a-zA-Z0-9]/.test(word) || GAMBLING_BRAND.test(word)) return true
    if (word.length > 4 && !GAMBLING_WHITELIST.test(word)) return true
    return !GAMBLING_KEEP.test(word)
  }
  if (['fraud', 'drug', 'weapon'].includes(category) && AD_PREFIX.test(word)) return true
  if (AD_SUFFIX.test(word)) {
    if (category === 'sexual' && SEXUAL_SUFFIX_WHITELIST.has(word)) return false
    return true
  }
  if (category === 'sexual' && BAD_SEXUAL.test(word)) return true
  if (category === 'weapon' && (BAD_WEAPON.test(word) || BAD_WEAPON_AD.test(word))) return true
  if (category === 'fraud' && FRAUD_AD.test(word)) return true
  if (category === 'drug' && /摇滚乐|药物毒品|^fuck|^q|q$|黄牙签|^操/.test(word)) return true
  if (category === 'minorSexual' && /q$/.test(word)) return true
  return false
}

