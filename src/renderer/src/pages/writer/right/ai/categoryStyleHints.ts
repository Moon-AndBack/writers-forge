/** 全量条目（178 条，字段命名版；顺序与 `CATEGORY_STYLE_ROWS` 一致）。 */
export const CATEGORY_STYLE_ENTRIES: readonly CategoryStyleEntry[] = CATEGORY_STYLE_ROWS.map(
  ([originId, channel, level, name, hint]) => ({ originId, channel, level, name, hint })
)

/** 频道优先序：同一 `originId` 撞车时用于稳定排序（与种子频道顺序一致）。 */
const CHANNEL_RANK: Record<CategoryStyleChannel, number> = {
  male: 0,
  female: 1,
  publish: 2
}

/** `originId` → 同 ID 条目组（按「一级优先、再按频道序」排序，组内首条为主条目）。 */
const ENTRIES_BY_ORIGIN = new Map<number, CategoryStyleEntry[]>()
for (const entry of CATEGORY_STYLE_ENTRIES) {
  const bucket = ENTRIES_BY_ORIGIN.get(entry.originId)
  if (bucket) bucket.push(entry)
  else ENTRIES_BY_ORIGIN.set(entry.originId, [entry])
}
for (const bucket of ENTRIES_BY_ORIGIN.values()) {
  bucket.sort((a, b) => a.level - b.level || CHANNEL_RANK[a.channel] - CHANNEL_RANK[b.channel])
}

/**
 * 扁平索引：`originId` → 主条目提示（同 ID 撞车时取一级分类；一级之间再按频道序）。
 *
 * 键数 169 < 条目数 178：9 个 ID 在种子内重复（见 `AMBIGUOUS_ORIGIN_IDS`），对象键无法并存。
 * 需要精确区分时用 `getCategoryStyleHint(originId, name)`。
 */
export const CATEGORY_STYLE_HINTS: Record<number, string> = {}
for (const [originId, bucket] of ENTRIES_BY_ORIGIN) {
  const primary = bucket[0]
  if (primary) CATEGORY_STYLE_HINTS[originId] = primary.hint
}

/**
 * 官方 ID 重复的分类（种子事实：5 / 6 / 7 / 8 / 12 / 21 / 22 为男频一级与二级撞车，
 * 80 / 82 为男频二级与女频一级撞车）。仅凭 ID 无法唯一定位，须配合分类名。
 */
export const AMBIGUOUS_ORIGIN_IDS: readonly number[] = [...ENTRIES_BY_ORIGIN.entries()]
  .filter(([, bucket]) => bucket.length > 1)
  .map(([originId]) => originId)
  .sort((a, b) => a - b)

/**
 * 按官方分类 ID 取风格提示；无映射时返回空串。
 *
 * @param originId `categories.origin_id`；自定义分类为 null，调用方可直接透传。
 * @param name 分类名（可选）：同一 ID 对应多条时（`AMBIGUOUS_ORIGIN_IDS`）传名称可精确命中；
 *   不传或名称不匹配时回落到该 ID 的主条目（一级优先）。
 */
export function getCategoryStyleHint(
  originId: number | null | undefined,
  name?: string | null
): string {
  if (originId === null || originId === undefined) return ''
  const bucket = ENTRIES_BY_ORIGIN.get(originId)
  if (!bucket || bucket.length === 0) return ''
  if (bucket.length > 1 && name) {
    const matched = bucket.find((entry) => entry.name === name)
    if (matched) return matched.hint
  }
  return bucket[0]?.hint ?? ''
}
